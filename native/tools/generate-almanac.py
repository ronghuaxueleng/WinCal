"""Generate embedded data; development only: pip install lunar_python==1.4.8."""
from pathlib import Path
from datetime import date, timedelta
from lunar_python import Solar
from lunar_python.util import LunarUtil
import importlib.metadata

assert importlib.metadata.version("lunar_python") == "1.4.8"
root = Path(__file__).resolve().parents[1]
vendor = root / "third_party" / "lunar"
vendor.mkdir(parents=True, exist_ok=True)
lines = ["// Generated by tools/generate-almanac.py from lunar_python 1.4.8 (MIT).",
         "#pragma once", "#include <array>", "#include <string_view>",
         "namespace wincal::almanac_data {",
         "inline constexpr std::wstring_view Activities[]{"]
lines += ['    L"' + s + '",' for s in LunarUtil._LunarUtil__YI_JI]
lines += ["};", "inline constexpr std::string_view DayRules ="]
rules = LunarUtil._LunarUtil__DAY_YI_JI
lines += ['    "' + rules[i:i+100] + '"' for i in range(0, len(rules), 100)]
lines += [";", "inline constexpr std::array<std::array<int, 24>, 201> SolarTerms{{"]
for year in range(1900, 2101):
    terms = Solar.fromYmd(year, 6, 1).getLunar().getJieQiTable()
    days = sorted(v.getMonth()*100+v.getDay() for v in terms.values() if v.getYear() == year)
    assert len(days) == 24
    lines.append("    {{" + ",".join(map(str, days)) + "}}, // " + str(year))
lines += ["}};", "}"]
(vendor / "almanac_data.h").write_text("\n".join(lines) + "\n", encoding="utf-8")

# Reference output from the original library, including each 2026 month boundary.
dates = {date(y, m, d) for y in (1900, 1950, 2000, 2025, 2026, 2100)
         for m, d in ((1, 1), (2, 4), (6, 21), (11, 7), (12, 31))}
for term in Solar.fromYmd(2026, 6, 1).getLunar().getJieQiTable().values():
    if term.getYear() == 2026:
        boundary = date(2026, term.getMonth(), term.getDay())
        dates.update((boundary-timedelta(days=1), boundary, boundary+timedelta(days=1)))
fixtures = ["// Generated reference results from lunar_python 1.4.8.",
            "struct AlmanacFixture { int year, month, day; const wchar_t *monthPillar, *dayPillar, *yi, *ji; };",
            "constexpr AlmanacFixture AlmanacFixtures[]{"]
for d in sorted(dates):
    lunar = Solar.fromYmd(d.year, d.month, d.day).getLunar()
    values = (lunar.getMonthInGanZhi(), lunar.getDayInGanZhi(),
              " · ".join(lunar.getDayYi()), " · ".join(lunar.getDayJi()))
    fixtures.append("    {" + f"{d.year},{d.month},{d.day}," +
                    ",".join('L"'+s+'"' for s in values) + "},")
fixtures += ["};"]
(root / "tests" / "almanac_fixtures.h").write_text("\n".join(fixtures)+"\n", encoding="utf-8")
print(f"Generated 201 solar-term years, {len(dates)} reference dates.")
