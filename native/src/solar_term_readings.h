inline const SolarTermReading* SolarTermReadingForDate(int year, int month, int day)
{
    const auto date = std::chrono::year{year}/static_cast<unsigned>(month)/static_cast<unsigned>(day);
    if (!date.ok() || year < 1900 || year > 2100) return nullptr;
    const auto dates = SolarTermDates(year);
    for (size_t i = 0; i < dates.size(); ++i)
        if (dates[i] == month * 100 + day) return &SolarTermReadings[i];
    return nullptr;
}
